#!/usr/bin/env node
// Turns the Lucide SVGs in design/icons/ into Compose ImageVectors (android/ui-kit) and ships the
// ISC licence text with the app. No dependencies.
// Run: node design/tools/build-icons.mjs   (--check: exit 1 if the outputs are stale)
//
// Lucide icons use four elements (path, rect, line, circle), all stroke-only at 24 x 24. Each element
// is rewritten as one SVG path string; the Kotlin side draws them with stroke 1.5, round caps and joins.

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const designDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = join(designDir, "..");
const iconDir = join(designDir, "icons");
const uikit = join(repoRoot, "android", "ui-kit", "src", "main");
const kotlinFile = join(uikit, "kotlin", "app", "overdrive", "uikit", "icons", "OverdriveIcons.kt");
const licenceFile = join(uikit, "assets", "licenses", "lucide-ISC.txt");
const macosRoot = join(repoRoot, "macos", "Overdrive");
const swiftFile = join(macosRoot, "Design", "Generated", "OverdriveIcons.swift");
const macosLicenceFile = join(macosRoot, "Resources", "Licenses", "lucide-ISC.txt");

const fail = (message) => {
  console.error(`build-icons: ${message}`);
  process.exit(1);
};

const num = (n) => String(Math.round(n * 1000) / 1000);

const attrs = (tag) => {
  const out = {};
  for (const [, key, value] of tag.matchAll(/([a-zA-Z0-9-]+)="([^"]*)"/g)) out[key] = value;
  return out;
};

const rectPath = ({ x = "0", y = "0", width, height, rx = "0" }) => {
  const [px, py, w, h] = [x, y, width, height].map(Number);
  const r = Math.min(Number(rx), w / 2, h / 2);
  if (r === 0) return `M${num(px)} ${num(py)}H${num(px + w)}V${num(py + h)}H${num(px)}Z`;
  return [
    `M${num(px + r)} ${num(py)}`,
    `H${num(px + w - r)}`,
    `A${num(r)} ${num(r)} 0 0 1 ${num(px + w)} ${num(py + r)}`,
    `V${num(py + h - r)}`,
    `A${num(r)} ${num(r)} 0 0 1 ${num(px + w - r)} ${num(py + h)}`,
    `H${num(px + r)}`,
    `A${num(r)} ${num(r)} 0 0 1 ${num(px)} ${num(py + h - r)}`,
    `V${num(py + r)}`,
    `A${num(r)} ${num(r)} 0 0 1 ${num(px + r)} ${num(py)}`,
    "Z",
  ].join("");
};

const circlePath = ({ cx, cy, r }) => {
  const [x, y, rad] = [cx, cy, r].map(Number);
  return `M${num(x - rad)} ${num(y)}A${num(rad)} ${num(rad)} 0 1 0 ${num(x + rad)} ${num(y)}A${num(rad)} ${num(rad)} 0 1 0 ${num(x - rad)} ${num(y)}Z`;
};

const linePath = ({ x1, y1, x2, y2 }) => `M${x1} ${y1}L${x2} ${y2}`;

const parseIcon = (file, text) => {
  if (!/viewBox="0 0 24 24"/.test(text)) fail(`${file}: expected viewBox 0 0 24 24`);
  const paths = [];
  for (const [tag] of text.matchAll(/<(path|rect|line|circle)\b[^>]*>/g)) {
    const kind = tag.slice(1).split(/[\s/>]/)[0];
    const a = attrs(tag);
    if (kind === "path") paths.push(a.d);
    else if (kind === "rect") paths.push(rectPath(a));
    else if (kind === "line") paths.push(linePath(a));
    else paths.push(circlePath(a));
  }
  if (/<(polyline|polygon|ellipse)\b/.test(text)) fail(`${file}: unsupported element`);
  if (paths.length === 0 || paths.some((p) => !p)) fail(`${file}: no drawable elements`);
  return paths;
};

const pascal = (name) =>
  name
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");

const files = readdirSync(iconDir)
  .filter((f) => f.endsWith(".svg"))
  .sort();

const camel = (name) => {
  const p = pascal(name);
  return p[0].toLowerCase() + p.slice(1);
};

const iconEntries = files.map((file) => {
  const name = file.replace(/\.svg$/, "");
  const paths = parseIcon(file, readFileSync(join(iconDir, file), "utf8"));
  return { name, pascalName: pascal(name), camelName: camel(name), paths };
});

const members = iconEntries.map(({ name, pascalName, paths }) => {
  const args = paths.map((p) => `        "${p}",`).join("\n");
  return `    val ${pascalName}: ImageVector by lazy {\n      lucide(\n        "${name}",\n${args}\n      )\n    }`;
});

const swiftCases = iconEntries
  .map(({ name, camelName }) => `    case ${camelName} = "${name}"`)
  .join("\n");
const swiftSwitch = iconEntries
  .map(({ camelName, paths }) => {
    const items = paths.map((p) => `            "${p}",`).join("\n");
    return `        case .${camelName}:\n            [\n${items}\n            ]`;
  })
  .join("\n");

const swift = `// GENERATED by design/tools/build-icons.mjs from design/icons/*.svg. Do not edit.
// Icons: Lucide (ISC licence), shipped in Resources/Licenses/lucide-ISC.txt.

import Foundation
import SwiftUI

/// The Lucide icon subset used by Overdrive, authored on a 24 x 24 stroke grid (stroke 1.5, round caps and joins).
public enum OverdriveIcon: String, CaseIterable, Sendable {
${swiftCases}

    public var svgPaths: [String] {
        switch self {
${swiftSwitch}
        }
    }
}

/// Renders an Overdrive Lucide icon scaled to the target rect.
public struct OverdriveIconShape: Shape, Sendable {
    public let icon: OverdriveIcon

    public init(icon: OverdriveIcon) {
        self.icon = icon
    }

    public func path(in rect: CGRect) -> Path {
        let sx = rect.width / 24.0
        let sy = rect.height / 24.0
        let scale = min(sx, sy)
        let ox = rect.minX + (rect.width - 24.0 * scale) / 2.0
        let oy = rect.minY + (rect.height - 24.0 * scale) / 2.0
        var out = Path()
        for d in icon.svgPaths {
            out.addPath(SvgPathParser.parse(d))
        }
        let transform = CGAffineTransform(translationX: ox, y: oy).scaledBy(x: scale, y: scale)
        return out.applying(transform)
    }
}

/// Minimal W3C SVG path-data parser supporting all commands emitted by Lucide icons (M/m, L/l, H/h, V/v, C/c, S/s, Q/q, T/t, A/a, Z/z).
enum SvgPathParser {
    static func parse(_ data: String) -> Path {
        var path = Path()
        var scanner = TokenScanner(data)
        var current = CGPoint.zero
        var subpathStart = CGPoint.zero
        var lastControl: CGPoint?
        var lastCommand: Character = " "

        while let cmd = scanner.nextCommand(previous: lastCommand) {
            lastCommand = cmd
            switch cmd {
            case "M", "m":
                guard let x = scanner.nextNumber(), let y = scanner.nextNumber() else { break }
                let pt = cmd == "m" ? CGPoint(x: current.x + x, y: current.y + y) : CGPoint(x: x, y: y)
                path.move(to: pt)
                current = pt
                subpathStart = pt
                lastControl = nil
                lastCommand = cmd == "m" ? "l" : "L"
            case "L", "l":
                guard let x = scanner.nextNumber(), let y = scanner.nextNumber() else { break }
                let pt = cmd == "l" ? CGPoint(x: current.x + x, y: current.y + y) : CGPoint(x: x, y: y)
                path.addLine(to: pt)
                current = pt
                lastControl = nil
            case "H", "h":
                guard let x = scanner.nextNumber() else { break }
                let pt = CGPoint(x: cmd == "h" ? current.x + x : x, y: current.y)
                path.addLine(to: pt)
                current = pt
                lastControl = nil
            case "V", "v":
                guard let y = scanner.nextNumber() else { break }
                let pt = CGPoint(x: current.x, y: cmd == "v" ? current.y + y : y)
                path.addLine(to: pt)
                current = pt
                lastControl = nil
            case "C", "c":
                guard let x1 = scanner.nextNumber(), let y1 = scanner.nextNumber(),
                      let x2 = scanner.nextNumber(), let y2 = scanner.nextNumber(),
                      let x = scanner.nextNumber(), let y = scanner.nextNumber() else { break }
                let rel = cmd == "c"
                let c1 = CGPoint(x: rel ? current.x + x1 : x1, y: rel ? current.y + y1 : y1)
                let c2 = CGPoint(x: rel ? current.x + x2 : x2, y: rel ? current.y + y2 : y2)
                let end = CGPoint(x: rel ? current.x + x : x, y: rel ? current.y + y : y)
                path.addCurve(to: end, control1: c1, control2: c2)
                current = end
                lastControl = c2
            case "S", "s":
                guard let x2 = scanner.nextNumber(), let y2 = scanner.nextNumber(),
                      let x = scanner.nextNumber(), let y = scanner.nextNumber() else { break }
                let rel = cmd == "s"
                let c1 = reflected(lastControl, around: current)
                let c2 = CGPoint(x: rel ? current.x + x2 : x2, y: rel ? current.y + y2 : y2)
                let end = CGPoint(x: rel ? current.x + x : x, y: rel ? current.y + y : y)
                path.addCurve(to: end, control1: c1, control2: c2)
                current = end
                lastControl = c2
            case "Q", "q":
                guard let x1 = scanner.nextNumber(), let y1 = scanner.nextNumber(),
                      let x = scanner.nextNumber(), let y = scanner.nextNumber() else { break }
                let rel = cmd == "q"
                let c1 = CGPoint(x: rel ? current.x + x1 : x1, y: rel ? current.y + y1 : y1)
                let end = CGPoint(x: rel ? current.x + x : x, y: rel ? current.y + y : y)
                path.addQuadCurve(to: end, control: c1)
                current = end
                lastControl = c1
            case "T", "t":
                guard let x = scanner.nextNumber(), let y = scanner.nextNumber() else { break }
                let rel = cmd == "t"
                let c1 = reflected(lastControl, around: current)
                let end = CGPoint(x: rel ? current.x + x : x, y: rel ? current.y + y : y)
                path.addQuadCurve(to: end, control: c1)
                current = end
                lastControl = c1
            case "A", "a":
                guard let rx = scanner.nextNumber(), let ry = scanner.nextNumber(),
                      let rot = scanner.nextNumber(),
                      let largeArc = scanner.nextFlag(), let sweep = scanner.nextFlag(),
                      let x = scanner.nextNumber(), let y = scanner.nextNumber() else { break }
                let end = cmd == "a" ? CGPoint(x: current.x + x, y: current.y + y) : CGPoint(x: x, y: y)
                addArc(to: &path, from: current, to: end, rx: rx, ry: ry, rotationDeg: rot, largeArc: largeArc, sweep: sweep)
                current = end
                lastControl = nil
            case "Z", "z":
                path.closeSubpath()
                current = subpathStart
                lastControl = nil
            default:
                break
            }
        }
        return path
    }

    private static func reflected(_ control: CGPoint?, around point: CGPoint) -> CGPoint {
        guard let c = control else { return point }
        return CGPoint(x: 2 * point.x - c.x, y: 2 * point.y - c.y)
    }

    private static func addArc(
        to path: inout Path,
        from p1: CGPoint,
        to p2: CGPoint,
        rx rawRx: CGFloat,
        ry rawRy: CGFloat,
        rotationDeg: CGFloat,
        largeArc: Bool,
        sweep: Bool
    ) {
        guard p1 != p2 else { return }
        var rx = abs(rawRx)
        var ry = abs(rawRy)
        guard rx > 1e-6, ry > 1e-6 else {
            path.addLine(to: p2)
            return
        }
        let phi = rotationDeg * .pi / 180.0
        let cosPhi = cos(phi)
        let sinPhi = sin(phi)
        let dx2 = (p1.x - p2.x) / 2.0
        let dy2 = (p1.y - p2.y) / 2.0
        let x1p = cosPhi * dx2 + sinPhi * dy2
        let y1p = -sinPhi * dx2 + cosPhi * dy2

        let lambda = (x1p * x1p) / (rx * rx) + (y1p * y1p) / (ry * ry)
        if lambda > 1.0 {
            let root = sqrt(lambda)
            rx *= root
            ry *= root
        }

        let rx2 = rx * rx
        let ry2 = ry * ry
        let x1p2 = x1p * x1p
        let y1p2 = y1p * y1p
        let num = max(0.0, rx2 * ry2 - rx2 * y1p2 - ry2 * x1p2)
        let den = rx2 * y1p2 + ry2 * x1p2
        let factor = den > 1e-9 ? sqrt(num / den) * (largeArc == sweep ? -1.0 : 1.0) : 0.0
        let cxp = factor * (rx * y1p / ry)
        let cyp = factor * (-ry * x1p / rx)

        let cx = cosPhi * cxp - sinPhi * cyp + (p1.x + p2.x) / 2.0
        let cy = sinPhi * cxp + cosPhi * cyp + (p1.y + p2.y) / 2.0

        func angle(_ ux: CGFloat, _ uy: CGFloat, _ vx: CGFloat, _ vy: CGFloat) -> CGFloat {
            let dot = ux * vx + uy * vy
            let len = max(1e-9, sqrt(ux * ux + uy * uy) * sqrt(vx * vx + vy * vy))
            let clamped = max(-1.0, min(1.0, dot / len))
            let a = acos(clamped)
            return (ux * vy - uy * vx) < 0 ? -a : a
        }

        let ux = (x1p - cxp) / rx
        let uy = (y1p - cyp) / ry
        let vx = (-x1p - cxp) / rx
        let vy = (-y1p - cyp) / ry
        let startAngle = angle(1, 0, ux, uy)
        var deltaAngle = angle(ux, uy, vx, vy)
        if !sweep && deltaAngle > 0 { deltaAngle -= 2 * .pi }
        if sweep && deltaAngle < 0 { deltaAngle += 2 * .pi }

        let segments = max(1, Int(ceil(abs(deltaAngle) / (.pi / 2.0))))
        let step = deltaAngle / CGFloat(segments)
        let alpha = (4.0 / 3.0) * tan(step / 4.0)

        for i in 0..<segments {
            let t1 = startAngle + CGFloat(i) * step
            let t2 = t1 + step
            let cos1 = cos(t1), sin1 = sin(t1)
            let cos2 = cos(t2), sin2 = sin(t2)
            let q1 = CGPoint(x: cos1 - alpha * sin1, y: sin1 + alpha * cos1)
            let q2 = CGPoint(x: cos2 + alpha * sin2, y: sin2 - alpha * cos2)
            let e = CGPoint(x: cos2, y: sin2)
            func map(_ p: CGPoint) -> CGPoint {
                let x = p.x * rx
                let y = p.y * ry
                return CGPoint(x: cosPhi * x - sinPhi * y + cx, y: sinPhi * x + cosPhi * y + cy)
            }
            path.addCurve(to: map(e), control1: map(q1), control2: map(q2))
        }
    }

    private struct TokenScanner {
        private let chars: [Character]
        private var index = 0

        init(_ text: String) {
            self.chars = Array(text)
        }

        private mutating func skipSeparators() {
            while index < chars.count && (chars[index].isWhitespace || chars[index] == ",") {
                index += 1
            }
        }

        mutating func nextCommand(previous: Character) -> Character? {
            skipSeparators()
            guard index < chars.count else { return nil }
            let c = chars[index]
            if c.isLetter {
                index += 1
                return c
            }
            return previous != " " ? previous : nil
        }

        mutating func nextFlag() -> Bool? {
            skipSeparators()
            guard index < chars.count else { return nil }
            let c = chars[index]
            if c == "0" || c == "1" {
                index += 1
                return c == "1"
            }
            return nil
        }

        mutating func nextNumber() -> CGFloat? {
            skipSeparators()
            guard index < chars.count else { return nil }
            let start = index
            if chars[index] == "+" || chars[index] == "-" { index += 1 }
            var sawDot = false
            var sawExp = false
            while index < chars.count {
                let c = chars[index]
                if c.isNumber {
                    index += 1
                } else if c == "." && !sawDot && !sawExp {
                    sawDot = true
                    index += 1
                } else if (c == "e" || c == "E") && !sawExp {
                    sawExp = true
                    index += 1
                    if index < chars.count && (chars[index] == "+" || chars[index] == "-") { index += 1 }
                } else {
                    break
                }
            }
            guard index > start, let value = Double(String(chars[start..<index])) else { return nil }
            return CGFloat(value)
        }
    }
}
`;

const kotlin = `// GENERATED by design/tools/build-icons.mjs from design/icons/*.svg. Do not edit.
// Icons: Lucide (ISC licence), shipped in assets/licenses/lucide-ISC.txt.

package app.overdrive.uikit.icons

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

/** The Lucide subset the app uses, stroke 1.5, drawn black: tint them when painting. */
object OverdriveIcons {
${members.join("\n\n")}

    /** Every icon with its Lucide name, for previews and tests. */
    val all: List<Pair<String, ImageVector>> by lazy {
        listOf(
${files.map((f) => `            "${f.replace(/\.svg$/, "")}" to ${pascal(f.replace(/\.svg$/, ""))},`).join("\n")}
        )
    }
}

private fun lucide(
    name: String,
    vararg paths: String,
): ImageVector =
    ImageVector
        .Builder(
            name = name,
            defaultWidth = 24.dp,
            defaultHeight = 24.dp,
            viewportWidth = 24f,
            viewportHeight = 24f,
        ).apply {
            for (path in paths) {
                addPath(
                    pathData = addPathNodes(path),
                    stroke = SolidColor(Color.Black),
                    strokeLineWidth = 1.5f,
                    strokeLineCap = StrokeCap.Round,
                    strokeLineJoin = StrokeJoin.Round,
                )
            }
        }.build()
`;

const outputs = [
  { path: kotlinFile, data: Buffer.from(kotlin) },
  { path: licenceFile, data: readFileSync(join(iconDir, "LICENSE.txt")) },
  { path: swiftFile, data: Buffer.from(swift) },
  { path: macosLicenceFile, data: readFileSync(join(iconDir, "LICENSE.txt")) },
];

if (process.argv.includes("--check")) {
  const stale = outputs.filter((o) => !existsSync(o.path) || !readFileSync(o.path).equals(o.data));
  if (stale.length > 0) {
    for (const o of stale) console.error(`stale: ${relative(repoRoot, o.path)}`);
    console.error("run: node design/tools/build-icons.mjs");
    process.exit(1);
  }
  console.log("icons up to date");
} else {
  for (const o of outputs) {
    mkdirSync(dirname(o.path), { recursive: true });
    writeFileSync(o.path, o.data);
    console.log(`wrote ${relative(repoRoot, o.path)}`);
  }
}
