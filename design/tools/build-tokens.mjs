#!/usr/bin/env node
// Reads design/tokens.json and writes design/mockups/tokens.css (CSS custom properties).
// No dependencies. Run: node design/tools/build-tokens.mjs
// 1 dp = 1 px and 1 sp = 1 px in the mock-ups; screenshots are taken at device scale factor 2.
// A Kotlin (Compose) output is to be added by the ui-kit implementation.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const designDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(join(designDir, "tokens.json"), "utf8"));

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const px = (n) => `${n}px`;
const lines = [];
const decl = (name, value) => lines.push(`  --${name}: ${value};`);
const section = (title) => lines.push("", `  /* ${title} */`);

const tokenValue = (entry) => (typeof entry === "object" && entry !== null ? entry.value : entry);
const isToken = (key) => !key.startsWith("$") && key !== "rules" && key !== "use";

section("Colour: neutrals");
for (const [k, v] of Object.entries(tokens.color.neutral)) {
  if (isToken(k)) decl(`color-${kebab(k)}`, tokenValue(v));
}
section("Colour: text");
for (const [k, v] of Object.entries(tokens.color.text)) {
  if (isToken(k)) decl(`color-text-${kebab(k)}`, tokenValue(v));
}
section("Colour: power zones (the only accent)");
for (const [k, v] of Object.entries(tokens.color.zone)) {
  if (isToken(k)) decl(`zone-${k.slice(1)}`, v.value);
}
decl("zone-past-alpha", tokens.color.zone.rules.pastAlpha);
decl("color-overlay-backing", tokens.color.overlay.backing.value);
decl("color-overlay-border", tokens.color.overlay.border.value);
decl("color-scrim", tokens.color.scrim.value);

section("Typography");
const fam = tokens.typography.family.sans.value;
decl("font-sans", `"${fam}", system-ui, sans-serif`);
decl("font-numerals", `"${tokens.typography.numerals.fontFeatureSettings}"`);
for (const [k, t] of Object.entries(tokens.typography.scale)) {
  if (!isToken(k)) continue;
  const n = kebab(k);
  decl(`type-${n}-size`, px(t.size));
  decl(`type-${n}-line`, px(t.lineHeight));
  decl(`type-${n}-weight`, t.weight);
  decl(`type-${n}-tracking`, `${t.tracking}em`);
}

section("Space, radius, stroke, size");
for (const [k, v] of Object.entries(tokens.space))
  if (isToken(k)) decl(`space-${k.slice(1)}`, px(v));
for (const [k, v] of Object.entries(tokens.radius)) if (isToken(k)) decl(`radius-${k}`, px(v));
for (const [k, v] of Object.entries(tokens.stroke))
  if (isToken(k)) decl(`stroke-${kebab(k)}`, px(v));
for (const [k, v] of Object.entries(tokens.size)) if (isToken(k)) decl(`size-${kebab(k)}`, px(v));

section("Overlay");
const o = tokens.overlay;
decl("overlay-opacity", o.opacity.default);
decl("overlay-pad-x", px(o.padding.horizontal));
decl("overlay-pad-y", px(o.padding.vertical));
decl("overlay-cell-gap", px(o.cellGap));
decl("overlay-label-gap", px(o.labelValueGap));
decl("overlay-radius", px(o.radius));
decl("overlay-width", px(o.compact.width));
decl("overlay-compact-height", px(o.compact.height));
decl("overlay-section-gap", px(o.detailed.sectionGap));
decl("overlay-profile-height", px(o.detailed.profileHeight));
for (const [k, s] of Object.entries(o.compact.slots)) {
  if (isToken(k)) decl(`overlay-slot-${kebab(k)}`, px(s.width));
}

section("Chart");
decl("chart-step-gap", px(tokens.chart.profile.stepGap));
decl("chart-bar-max", px(tokens.chart.bar.maxThickness));
decl("chart-bar-radius", px(tokens.chart.bar.endRadius));

section("Motion");
for (const [k, v] of Object.entries(tokens.motion.duration)) decl(`motion-${kebab(k)}`, `${v}ms`);
for (const [k, v] of Object.entries(tokens.motion.easing)) decl(`ease-${kebab(k)}`, v);

const fontFaces = Object.entries(tokens.typography.family.sans.files)
  .map(
    ([weight, file]) =>
      `@font-face {\n  font-family: "${fam}";\n  src: url("../fonts/${file.split("/").pop()}") format("truetype");\n  font-weight: ${weight};\n  font-style: normal;\n  font-display: block;\n}`,
  )
  .join("\n\n");

const css = `/* Generated by design/tools/build-tokens.mjs from design/tokens.json. Do not edit. */

${fontFaces}

:root {
  color-scheme: dark;${lines.join("\n")}
}
`;

const out = join(designDir, "mockups", "tokens.css");
writeFileSync(out, css);
console.log(`wrote ${out} (${lines.filter((l) => l.startsWith("  --")).length} properties)`);
