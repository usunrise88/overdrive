package app.overdrive.core.ble

import app.overdrive.core.ble.integration.RecordedRide
import app.overdrive.core.ble.integration.SyntheticRide
import app.overdrive.core.ble.integration.recordLiveRide
import app.overdrive.core.ble.integration.replayRide
import app.overdrive.core.ble.recording.BleDirection
import app.overdrive.core.ble.recording.BleSessionFormat
import kotlinx.coroutines.ExperimentalCoroutinesApi
import kotlinx.coroutines.test.runTest
import java.io.File
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * The synthetic BLE sessions of `contracts/fixtures/ble/` (docs/protocols/ftms-hr.md §7.1, spec §7.5): generated by running
 * a ride live over the fake Bluetooth with the recorder on, never real recordings (the repository is public). The files are
 * golden: this test fails if the generator and the committed files disagree, and every file replays through the real
 * adapters and engine into the ride that produced it.
 *
 * To regenerate after an intended change: `cd core && ./gradlew jvmTest -PregenerateBleFixtures=true`, then review the diff.
 */
@OptIn(ExperimentalCoroutinesApi::class)
class BleSessionFixturesTest {
    private val directory = File(System.getProperty("overdrive.contracts.dir"), "fixtures/ble")
    private val regenerate = System.getProperty("overdrive.ble.regenerate") == "true"

    private fun file(
        scenario: SyntheticRide,
        role: String,
    ) = File(directory, "${scenario.stem}.$role.session.txt")

    private fun live(scenario: SyntheticRide): RecordedRide {
        lateinit var recorded: RecordedRide
        runTest { recorded = recordLiveRide(scenario) }
        return recorded
    }

    @Test
    fun `the committed fixtures are what the generator produces`() {
        for (scenario in SyntheticRide.entries) {
            val recorded = live(scenario)
            for ((role, text) in listOf("trainer" to recorded.trainerSession, "strap" to recorded.strapSession)) {
                val target = file(scenario, role)
                if (regenerate) {
                    directory.mkdirs()
                    target.writeText(text)
                }
                assertTrue(
                    target.exists(),
                    "missing fixture ${target.name}; regenerate with -PregenerateBleFixtures=true",
                )
                assertEquals(
                    target.readText(),
                    text,
                    "${target.name} is stale; regenerate with -PregenerateBleFixtures=true and review the diff",
                )
            }
        }
    }

    @Test
    fun `each committed fixture pair replays into the ride that produced it`() {
        for (scenario in SyntheticRide.entries) {
            val recorded = live(scenario)
            val trainer = file(scenario, "trainer").readText()
            val strap = file(scenario, "strap").readText()
            lateinit var replayed: app.overdrive.core.record.RideRecord
            runTest { replayed = replayRide(scenario, trainer, strap) }
            assertEquals(recorded.record, replayed, scenario.stem)
        }
    }

    @Test
    fun `the fixtures are synthetic and anonymous`() {
        for (scenario in SyntheticRide.entries) {
            for (role in listOf("trainer", "strap")) {
                val text = file(scenario, role).readText()
                val parsed = BleSessionFormat.parseWithDiagnostics(text)
                assertEquals(BleSessionFormat.VERSION, parsed.version)
                assertEquals(0, parsed.skippedLines)
                assertTrue(
                    parsed.session.model in setOf("D500", "HR7"),
                    "only the advertised model name: ${parsed.session.model}",
                )
                assertTrue(
                    text.length < 30_000,
                    "${scenario.stem}.$role is ${text.length} characters, keep fixtures short",
                )
                assertTrue(
                    text.lines().none {
                        it.startsWith("#") && !it.startsWith("# overdrive-ble-session") &&
                            !it.startsWith("# model ")
                    },
                )
                // No redacted values were needed, so nothing identifying was even read, and nothing looks like an address.
                assertTrue(parsed.session.events.none { it.data == "*" })
                assertTrue(!Regex("([0-9A-Fa-f]{2}[:-]){5}[0-9A-Fa-f]{2}").containsMatchIn(text))
                val directions = parsed.session.events.map { it.direction }.toSet()
                assertTrue(BleDirection.NOTIFICATION in directions && BleDirection.STATE in directions)
            }
        }
    }
}
