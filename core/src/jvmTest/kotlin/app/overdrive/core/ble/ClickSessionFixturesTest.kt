package app.overdrive.core.ble

import app.overdrive.core.ble.recording.BleDirection
import app.overdrive.core.ble.recording.BleSessionFormat
import app.overdrive.core.click.integration.RecordedClick
import app.overdrive.core.click.integration.SyntheticClick
import app.overdrive.core.click.integration.recordLiveClick
import app.overdrive.core.click.integration.replayClick
import kotlinx.coroutines.ExperimentalCoroutinesApi
import kotlinx.coroutines.test.runTest
import java.io.File
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * The synthetic Click sessions, the `.click.session.txt` files of `contracts/fixtures/ble/` (docs/protocols/click-v2.md,
 * docs/adr/0011-click-gestures-and-sync-stub.md): generated by running a fake Click live over the fake Bluetooth with the
 * recorder on, never real recordings (the repository is public). The files are golden: this test fails if the generator and
 * the committed files disagree, and every file replays through the real adapter into what the live run showed.
 *
 * To regenerate after an intended change: `cd core && ./gradlew jvmTest -PregenerateBleFixtures=true`, then review the diff.
 */
@OptIn(ExperimentalCoroutinesApi::class)
class ClickSessionFixturesTest {
    private val directory = File(System.getProperty("overdrive.contracts.dir"), "fixtures/ble")
    private val regenerate = System.getProperty("overdrive.ble.regenerate") == "true"

    private fun file(scenario: SyntheticClick) = File(directory, "${scenario.stem}.click.session.txt")

    private fun live(scenario: SyntheticClick): RecordedClick {
        lateinit var recorded: RecordedClick
        runTest { recorded = recordLiveClick(scenario) }
        return recorded
    }

    @Test
    fun `the committed fixtures are what the generator produces`() {
        for (scenario in SyntheticClick.entries) {
            val text = live(scenario).session
            val target = file(scenario)
            if (regenerate) {
                directory.mkdirs()
                target.writeText(text)
            }
            assertTrue(target.exists(), "missing fixture ${target.name}; regenerate with -PregenerateBleFixtures=true")
            assertEquals(
                target.readText(),
                text,
                "${target.name} is stale; regenerate with -PregenerateBleFixtures=true and review the diff",
            )
        }
    }

    @Test
    fun `each committed fixture replays into what the live run showed`() {
        for (scenario in SyntheticClick.entries) {
            val recorded = live(scenario)
            lateinit var replayed: app.overdrive.core.click.integration.ClickObservation
            runTest { replayed = replayClick(scenario, file(scenario).readText()) }
            assertEquals(recorded.observation, replayed, scenario.stem)
        }
    }

    @Test
    fun `the fixtures are synthetic and anonymous`() {
        for (scenario in SyntheticClick.entries) {
            val text = file(scenario).readText()
            val parsed = BleSessionFormat.parseWithDiagnostics(text)
            assertEquals(BleSessionFormat.VERSION, parsed.version)
            assertEquals(0, parsed.skippedLines)
            assertEquals("Click", parsed.session.model, "only the advertised model name")
            assertTrue(text.length < 30_000, "${scenario.stem} is ${text.length} characters, keep fixtures short")
            assertTrue(
                text.lines().none {
                    it.startsWith("#") && !it.startsWith("# overdrive-ble-session") && !it.startsWith("# model ")
                },
            )
            // The only redacted value is the firmware revision, which the recorder's policy withholds.
            val redacted = parsed.session.events.filter { it.data == "*" }
            assertTrue(redacted.all { it.characteristic?.shortForm == "2A26" }, "redacted: $redacted")
            assertTrue(!Regex("([0-9A-Fa-f]{2}[:-]){5}[0-9A-Fa-f]{2}").containsMatchIn(text))
            assertTrue(!text.contains("1.2.0") && !text.contains("312E322E30"), "no firmware in the file")
            val directions = parsed.session.events.map { it.direction }.toSet()
            assertTrue(BleDirection.STATE in directions && BleDirection.DISCOVERY in directions)
        }
    }

    @Test
    fun `the handshake reply in a fixture carries only RideOn and its version`() {
        val text = file(SyntheticClick.BUTTONS).readText()
        val replies =
            BleSessionFormat
                .parse(text)
                .events
                .filter { it.direction == BleDirection.INDICATION && it.characteristic == ClickUuids.SYNC_TX }
        assertEquals(listOf("526964654F6E0203"), replies.map { it.data })
    }
}
