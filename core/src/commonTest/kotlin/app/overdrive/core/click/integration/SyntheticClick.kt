/**
 * Synthetic Click sessions, run live over the fake Bluetooth, recorded through the decorator and replayed: the source of the
 * `*.click.session.txt` fixtures of `contracts/fixtures/ble/`. Nothing here comes from a real controller: every byte is
 * generated by `FakeClick`, which is written from `docs/protocols/click-v2.md` and the protocol facts of the first bench
 * report (`docs/bench-reports/2026-11-18-first-ride.md`); no byte of a real recording is used. Unless a scenario says
 * otherwise the fake is the default `FakeClick`, which behaves like the real right puck: a bare `RideOn` reply and nothing
 * until a press. The firmware revision is redacted by the recorder's policy, as it would be for a real one.
 */
internal enum class SyntheticClick(
    /** File name stem: `<stem>.click.session.txt`. */
    val stem: String,
    /** How long the scenario runs, in milliseconds. */
    val durationMillis: Long,
) {
    /**
     * A Click **as the notes described it before the bench** (`FakeClickOptions.byNotes`: `RideOn 02 03`, a battery frame,
     * a heartbeat every five seconds): a tap, a hold, a chord, a held volume button, a battery report, the disconnect notice
     * and a frame nobody knows. Keeps the `02 03` path under golden test.
     */
    BUTTONS("click-buttons", 20_000),

    /**
     * **A model of the real right puck** (`FakeClickOptions.realPuck`, from the first bench report): the Zwift service with
     * the three vendor characteristics the app does not use, write without response only, an MTU of 251, a bare `RideOn`
     * reply, the unknown `0x2A` message right after the notifications are enabled, the battery by read only, and then
     * **nothing until a press**: five presses with the bits the bench saw (A, B, Y, Minus, Plus shift down), eight idle
     * seconds at the end.
     */
    REAL_PUCK("click-real-puck", 20_000),

    /** Plus is held when the link drops with status 8: its release is lost. Later a tap on B after the reconnect. */
    DROPOUT("click-dropout", 16_000),

    /** A locked controller that hides its service: every attempt finds no Zwift service and backs off. */
    LOCKED("click-locked", 10_000),

    /** A locked controller, unlocked through Zwift at 5 s: the next attempt connects and delivers. */
    UNLOCK("click-unlock", 15_000),

    /**
     * **Opt-in lock rule:** a controller that answers the handshake and then says nothing, with `silentMeansLocked = true`
     * set explicitly ([options]): needs unlocking after 30 s. With the default options the same controller is simply active
     * (bench report 1: a healthy Click is silent until a press).
     */
    SILENT("click-silent", 35_000),
    ;

    /** The adapter's options in this scenario: the defaults, except that [SILENT] switches its rule on. */
    fun options(): ClickOptions = if (this == SILENT) ClickOptions(silentMeansLocked = true) else ClickOptions()

    /** The simulated controller of this scenario. */
    fun fake(): FakeClick =
        FakeClick(
            when (this) {
                BUTTONS -> FakeClickOptions.byNotes()
                REAL_PUCK -> FakeClickOptions.realPuck()
                else -> FakeClickOptions()
            },
        ).also {
            it.lock =
                when (this) {
                    LOCKED, UNLOCK -> FakeClickLock.HIDDEN
                    SILENT -> FakeClickLock.SILENT
                    else -> FakeClickLock.NONE
                }
        }

    /** Scripts the rider and what goes wrong, at times on the world clock. */
    fun script(fake: FakeClick) {
        fake.script {
            when (this@SyntheticClick) {
                BUTTONS -> {
                    tap(ClickBits.PLUS, at = 3.seconds)
                    hold(ClickBits.Y, at = 5.seconds, duration = 700.milliseconds)
                    press(ClickBits.A or ClickBits.Z, at = 8.seconds)
                    release(ClickBits.A or ClickBits.Z, at = 8300.milliseconds)
                    hold(ClickBits.A, at = 10.seconds, duration = 1200.milliseconds)
                    battery(80, at = 14.seconds)
                    notice(at = 15.seconds)
                    frame(ClickEncoder.frame(0x3C, byteArrayOf(0x01, 0x02)), at = 16.seconds)
                }

                REAL_PUCK -> {
                    tap(ClickBits.A, at = 3.seconds, held = 120.milliseconds)
                    tap(ClickBits.B, at = 5.seconds)
                    hold(ClickBits.Y, at = 7.seconds, duration = 700.milliseconds)
                    tap(ClickBits.MINUS, at = 9.seconds)
                    tap(ClickBits.PLUS_SHIFT_DOWN, at = 11.seconds)
                }

                DROPOUT -> {
                    press(ClickBits.PLUS, at = 3.seconds)
                    drop(at = 3300.milliseconds)
                    release(ClickBits.PLUS, at = 4.seconds) // while the link is down: never reaches the host
                    tap(ClickBits.B, at = 9.seconds)
                }

                LOCKED -> {
                    Unit
                }

                UNLOCK -> {
                    unlock(at = 5.seconds)
                    tap(ClickBits.PLUS, at = 12.seconds)
                }

                SILENT -> {
                    Unit
                }
            }
        }
    }
}

/** What the rest of the app would have seen of a Click session: its button changes, its states and its battery. */
internal data class ClickObservation(
    val changes: List<ButtonChange>,
    val states: List<ClickState>,
    val battery: Int?,
    val events: List<ClickEvent>,
)

/** A live scenario's recording and what it showed. */
internal class RecordedClick(
    val session: String,
    val observation: ClickObservation,
)

private fun TestScope.observe(
    rig: BleRig,
    scenario: SyntheticClick,
    factory: app.overdrive.core.ble.GattTransportFactory,
    beforeRun: () -> Unit,
): Pair<ClickObservation, () -> Unit> {
    val click = rig.click(options = scenario.options(), factory = factory)
    val states = collectAll(click.state)
    val changes = collectAll(click.buttons)
    val events = collectAll(click.events)
    beforeRun()
    click.start()
    rig.advance(scenario.durationMillis)
    val observation = ClickObservation(changes.toList(), states.toList(), click.battery.value, events.toList())
    return observation to { click.close() }
}

/** Runs [scenario] live over the fake Bluetooth with the recorder on. */
@OptIn(ExperimentalCoroutinesApi::class)
internal fun TestScope.recordLiveClick(scenario: SyntheticClick): RecordedClick {
    val rig = BleRig(this)
    val fake = rig.addClick(scenario.fake())
    val lines = rig.recording(model = "Click")
    val (observation, stop) = observe(rig, scenario, lines.factory) { scenario.script(fake) }
    stop()
    rig.settle()
    lines.recorder.close()
    rig.settle()
    return RecordedClick(lines.lines.joinToString("\n", postfix = "\n"), observation)
}

/** Plays a recorded [session] back through the real adapter and returns what it showed. */
@OptIn(ExperimentalCoroutinesApi::class)
internal fun TestScope.replayClick(
    scenario: SyntheticClick,
    session: String,
): ClickObservation {
    val rig = BleRig(this)
    rig.ble.add(CLICK_ID, ReplayPeripheral(BleSessionFormat.parse(session)))
    val (observation, stop) = observe(rig, scenario, rig.ble) { }
    check(rig.ble.violations.isEmpty()) { "The replay broke the contract: ${rig.ble.violations}" }
    stop()
    return observation
}
